/**
 * 상황에 맞는 한 줄을 고른다.
 *
 * `seed` 를 넘기면 같은 값에는 같은 말이 나온다 —
 * 화면이 다시 그려질 때마다 대사가 바뀌면 읽던 사람이 놓친다.
 */
export function npcLine(npc: NpcDefinition, mood: NpcMood, seed = 0): string {
  const pool = npc.lines[mood];
  if (!pool || pool.length === 0) return npc.greeting;
  return pool[Math.abs(Math.floor(seed)) % pool.length];
}
